"""
Transmodel part of each Transmodel class, read from the Enterprise Architect model.

transmodel.ttl was exported from the Transmodel EA model without the part a class is defined in,
yet the part carries meaning: SINGLE JOURNEY is defined in "Part 10 - Alternative Modes (NM)", which
tells a reader it was introduced for new modes (issue #151). This module reads the package tree from
the model (a .qea file is an SQLite database) and renders one tmalign:transmodelPart literal per class:
the top-level package below the Transmodel root, such as "Part 10 - Alternative Modes (NM)". It never
changes the triples already in transmodel.ttl.

Requirements & design: Andrej Tibaut, Sara Guerra de Oliveira (UM KGPI)
Crafted by: AI coding agents
Created: 2026-10-26  |  Modified: 2026-10-26
"""

from __future__ import annotations

import re
import sqlite3
from collections import defaultdict
from pathlib import Path

PART_PREDICATE = "https://napcore.eu/ontology/transmodel-alignment#transmodelPart"
SECTION_MARKER = "# ---- Transmodel parts (generated by add_transmodel_parts; do not edit below) ----"
TRANSMODEL_ROOT_PREFIX = "Transmodel v6.2"

_CLASS_DECLARATION = re.compile(r"^tm:([A-Za-z0-9_]+) a owl:Class", re.M)


def class_key(name: str) -> str:
    """The tm: local name of an EA class name ("PRE-ASSIGNED FARE PRODUCT" -> PRE_ASSIGNED_FARE_PRODUCT)."""
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")


def read_parts(model_path: Path) -> dict[str, dict]:
    """The Transmodel part of each class below the Transmodel v6.2 root: {local name: {object id: part}}.

    A name can be defined twice (VEHICLE EQUIPMENT PROFILE in Part 1 and in Part 10); transmodel.ttl then
    names the second class with its object id (VEHICLE_EQUIPMENT_PROFILE_12709). Classes of the other
    models in the file (NeTEx and SIRI physical models, OSDM, ...) are ignored.
    """
    db = sqlite3.connect(f"file:{model_path}?mode=ro", uri=True)
    try:
        packages = {row[0]: (row[1], row[2]) for row in db.execute("SELECT Package_ID, Name, Parent_ID FROM t_package")}
        classes = db.execute(
            "SELECT Object_ID, Name, Package_ID FROM t_object WHERE Object_Type = 'Class' AND Name IS NOT NULL"
        )

        def chain(package_id: int) -> list[str]:
            names: list[str] = []
            seen: set[int] = set()
            while package_id in packages and package_id not in seen:
                seen.add(package_id)
                name, package_id = packages[package_id]
                names.append(name.strip())
            return list(reversed(names))

        parts: dict[str, dict] = defaultdict(dict)
        for object_id, name, package_id in classes:
            names = chain(package_id)
            if len(names) > 1 and names[0].startswith(TRANSMODEL_ROOT_PREFIX):
                parts[class_key(name)][object_id] = names[1]
        return dict(parts)
    finally:
        db.close()


def _literal(text: str) -> str:
    return '"' + text.replace("\\", "\\\\").replace('"', '\\"') + '"'


def _parts_for(local_name: str, classes: set[str], parts: dict[str, dict]) -> list[str]:
    """Part(s) of one tm: class.

    NAME_<object id> is that object's part; the plain NAME gets the parts of the objects that have no
    such suffixed class of their own.
    """
    suffixed = re.fullmatch(r"(.+)_(\d+)", local_name)
    if suffixed and int(suffixed.group(2)) in parts.get(suffixed.group(1), {}):
        return [parts[suffixed.group(1)][int(suffixed.group(2))]]
    by_object = parts.get(local_name, {})
    return sorted({part for object_id, part in by_object.items() if f"{local_name}_{object_id}" not in classes})


def add_part_section(ttl_text: str, parts: dict[str, dict], model_name: str) -> tuple[str, dict]:
    """Return transmodel.ttl with a part section for its classes, replacing an earlier section.

    Also returns counts: classes with one part, with several, and without any.
    """
    base = ttl_text.split(SECTION_MARKER, 1)[0].rstrip() + "\n"
    class_set = set(_CLASS_DECLARATION.findall(base))
    lines = [
        "",
        SECTION_MARKER,
        f"# Source: {model_name}, top-level packages below the {TRANSMODEL_ROOT_PREFIX} root.",
        f"@prefix tmalign: <{PART_PREDICATE.rsplit('#', 1)[0]}#> .",
        "",
    ]
    counts = {"one": 0, "several": 0, "none": 0}
    missing: list[str] = []
    for local_name in sorted(class_set):
        class_parts = _parts_for(local_name, class_set, parts)
        if not class_parts:
            counts["none"] += 1
            missing.append(local_name)
            continue
        counts["one" if len(class_parts) == 1 else "several"] += 1
        values = " , ".join(_literal(part) for part in class_parts)
        lines.append(f"tm:{local_name} tmalign:transmodelPart {values} .")
    counts["missing"] = missing
    return base + "\n".join(lines) + "\n", counts
