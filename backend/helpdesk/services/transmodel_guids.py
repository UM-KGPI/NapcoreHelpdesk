"""
EA GUID of each Transmodel class, read from the Enterprise Architect model.

transmodel.ttl was exported from the Transmodel EA model without a global identifier for its classes.
The EA GUID is that identifier: it stays the same across model releases (unlike EA's numeric object and
diagram IDs), and the Transmodel website can give everything else about a class, such as its part and
its diagrams (issue #151). This module reads the GUIDs from the model (a .qea file is an SQLite database)
and renders one tmalign:eaGuid literal per class. It never changes the triples already in transmodel.ttl.

Requirements & design: Andrej Tibaut, Sara Guerra de Oliveira (UM KGPI)
Crafted by: AI coding agents
Created: 2026-10-26  |  Modified: 2026-10-26
"""

from __future__ import annotations

import re
import sqlite3
from collections import defaultdict
from pathlib import Path

GUID_PREDICATE = "https://napcore.eu/ontology/transmodel-alignment#eaGuid"
SECTION_MARKER = "# ---- EA GUIDs (generated by add_transmodel_guids; do not edit below) ----"
TRANSMODEL_ROOT_PREFIX = "Transmodel v6.2"

_CLASS_DECLARATION = re.compile(r"^tm:([A-Za-z0-9_]+) a owl:Class", re.M)


def class_key(name: str) -> str:
    """The tm: local name of an EA class name ("PRE-ASSIGNED FARE PRODUCT" -> PRE_ASSIGNED_FARE_PRODUCT)."""
    return re.sub(r"[^A-Za-z0-9]+", "_", name).strip("_")


def read_guids(model_path: Path) -> dict[str, dict]:
    """The EA GUID of each class below the Transmodel v6.2 root: {local name: {object id: GUID}}.

    A name can be defined twice (VEHICLE EQUIPMENT PROFILE in Part 1 and in Part 10); transmodel.ttl then
    names the second class with its object id (VEHICLE_EQUIPMENT_PROFILE_12709). Classes of the other
    models in the file (NeTEx and SIRI physical models, OSDM, ...) are ignored.
    """
    db = sqlite3.connect(f"file:{model_path}?mode=ro", uri=True)
    try:
        packages = {row[0]: (row[1], row[2]) for row in db.execute("SELECT Package_ID, Name, Parent_ID FROM t_package")}
        classes = db.execute(
            "SELECT Object_ID, Name, Package_ID, ea_guid FROM t_object"
            " WHERE Object_Type = 'Class' AND Name IS NOT NULL AND ea_guid IS NOT NULL"
        )

        def root(package_id: int) -> str:
            name = ""
            seen: set[int] = set()
            while package_id in packages and package_id not in seen:
                seen.add(package_id)
                name, package_id = packages[package_id]
            return name.strip()

        guids: dict[str, dict] = defaultdict(dict)
        for object_id, name, package_id, guid in classes:
            if root(package_id).startswith(TRANSMODEL_ROOT_PREFIX):
                guids[class_key(name)][object_id] = guid
        return dict(guids)
    finally:
        db.close()


def _guids_for(local_name: str, classes: set[str], guids: dict[str, dict]) -> list[str]:
    """GUID(s) of one tm: class.

    NAME_<object id> is that object's GUID; the plain NAME gets the GUIDs of the objects that have no
    such suffixed class of their own.
    """
    suffixed = re.fullmatch(r"(.+)_(\d+)", local_name)
    if suffixed and int(suffixed.group(2)) in guids.get(suffixed.group(1), {}):
        return [guids[suffixed.group(1)][int(suffixed.group(2))]]
    by_object = guids.get(local_name, {})
    return sorted({guid for object_id, guid in by_object.items() if f"{local_name}_{object_id}" not in classes})


def add_guid_section(ttl_text: str, guids: dict[str, dict], model_name: str) -> tuple[str, dict]:
    """Return transmodel.ttl with a GUID section for its classes, replacing an earlier section.

    Also returns counts: classes with one GUID, with several, and without any.
    """
    base = ttl_text.split(SECTION_MARKER, 1)[0].rstrip() + "\n"
    class_set = set(_CLASS_DECLARATION.findall(base))
    lines = [
        "",
        SECTION_MARKER,
        f"# Source: {model_name}, classes below the {TRANSMODEL_ROOT_PREFIX} root.",
        f"@prefix tmalign: <{GUID_PREDICATE.rsplit('#', 1)[0]}#> .",
        "",
    ]
    counts = {"one": 0, "several": 0, "none": 0}
    missing: list[str] = []
    for local_name in sorted(class_set):
        class_guids = _guids_for(local_name, class_set, guids)
        if not class_guids:
            counts["none"] += 1
            missing.append(local_name)
            continue
        counts["one" if len(class_guids) == 1 else "several"] += 1
        values = " , ".join(f'"{guid}"' for guid in class_guids)
        lines.append(f"tm:{local_name} tmalign:eaGuid {values} .")
    counts["missing"] = missing
    return base + "\n".join(lines) + "\n", counts
