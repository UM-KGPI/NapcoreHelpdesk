"""
EA GUID of each Transmodel class: the section of transmodel.ttl that holds them.

The EA GUID is the global identifier of a class in the Transmodel Enterprise Architect model: it stays the same
across model releases (unlike EA's numeric object and diagram IDs), and the Transmodel website can give
everything else about a class, such as its part and its diagrams (issue #151). The builder of transmodel.ttl
(services/transmodel_model.py, manage.py build_transmodel_ontology) writes one tmalign:eaGuid literal per class
in a marked section at the end of the file; ontology_evidence reads it back for the ?guid= links.

Until 24 November the section was added afterwards by manage.py add_transmodel_guids, which matched classes to
model objects by name; the builder knows each class's object, so that command was removed. The section's
marker and form are unchanged.

Requirements & design: Andrej Tibaut, Sara Guerra de Oliveira (UM KGPI)
Created: 2026-10-26  |  Modified: 2026-11-24
"""

from __future__ import annotations

import re
from collections.abc import Iterable

GUID_PREDICATE = "https://napcore.eu/ontology/transmodel-alignment#eaGuid"
SECTION_MARKER = "# ---- EA GUIDs (generated by add_transmodel_guids; do not edit below) ----"
TRANSMODEL_ROOT_PREFIX = "Transmodel v6.2"


def guid_section(class_locals: Iterable[str], guids: dict[str, list[str]], model_name: str) -> str:
    """The GUID section for the classes, in the order given, to append to transmodel.ttl.

    guids: {local name: [GUID, ...]}; a class without a GUID gets no line."""
    lines = [
        "",
        SECTION_MARKER,
        f"# Source: {model_name}, classes below the {TRANSMODEL_ROOT_PREFIX} root.",
        f"@prefix tmalign: <{GUID_PREDICATE.rsplit('#', 1)[0]}#> .",
        "",
    ]
    for local_name in class_locals:
        if guids.get(local_name):
            values = " , ".join(f'"{guid}"' for guid in sorted(guids[local_name]))
            lines.append(f"tm:{local_name} tmalign:eaGuid {values} .")
    return "\n".join(lines) + "\n"


_GUID_TRIPLE = re.compile(r'^tm:([A-Za-z0-9_]+) tmalign:eaGuid "\{([^{}"]+)\}"', re.M)


def read_guid_section(ttl_text: str) -> dict[str, str]:
    """The EA GUID of each class from the generated section of transmodel.ttl, without braces.

    {local name: GUID}, e.g. {"SINGLE_JOURNEY": "8E3A5314-957E-4033-9057-F6F7530A0111"}. A class with
    several GUIDs gets the first one. Empty when the file has no GUID section.
    """
    _, marker, section = ttl_text.partition(SECTION_MARKER)
    return dict(_GUID_TRIPLE.findall(section)) if marker else {}
