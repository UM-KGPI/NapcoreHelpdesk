#!/usr/bin/env bash
# Production deploy script — runs on the server, started by the Deploy to Production workflow
# on the self-hosted runner (docs/production-deployment.md, section 5).
# Expected location on server: /opt/napcore-helpdesk/scripts/deploy.sh
set -euo pipefail

REPO_DIR="${REPO_DIR:-/opt/napcore-helpdesk}"
COMPOSE="docker compose -f ${REPO_DIR}/docker-compose.prod.yml"

cd "${REPO_DIR}"

if [[ -z "${DEPLOY_PULLED:-}" ]]; then
  echo "==> Pulling latest code"
  git pull origin main
  # Bash keeps executing the copy of this file it started with, so if the pull changed this
  # script, the rest of this run would use the old logic. Run the pulled copy instead.
  trace=""
  [[ $- == *x* ]] && trace="-x"
  DEPLOY_PULLED=1 exec bash ${trace} scripts/deploy.sh
fi

# The Transmodel EA HTML export (issue #151) lives in its own repository; nginx serves this
# checkout at /transmodel/. It is generated by Enterprise Architect and never edited here, so the
# checkout is reset to the repository each time (a re-export may rewrite its history). Runs
# before the maintenance page, so a failure stops the deploy with the site still up.
TRANSMODEL_HTML_REPO="${TRANSMODEL_HTML_REPO:-https://github.com/UM-KGPI/transmodel-html.git}"
TRANSMODEL_HTML_DIR="${REPO_DIR}/transmodel-html"
echo "==> Updating the Transmodel HTML export"
if [[ -d "${TRANSMODEL_HTML_DIR}/.git" ]]; then
  git -C "${TRANSMODEL_HTML_DIR}" fetch --depth 1 origin main
  git -C "${TRANSMODEL_HTML_DIR}" reset --hard FETCH_HEAD
else
  git clone --depth 1 "${TRANSMODEL_HTML_REPO}" "${TRANSMODEL_HTML_DIR}"
fi

echo "==> Building images"
# Without these, docker-compose.prod.yml falls back to defaults: the frontend shows its
# hardcoded "0.6.1" version, and the backend reports build reference "dev" and keeps a stale
# VERSION after a deployment that changed nothing else (see scripts/build_env.sh).
. scripts/build_env.sh
${COMPOSE} build --pull

# Maintenance page from here until the new backend is ready (nginx checks for this file,
# see frontend/nginx-frontend.conf). The build above runs with the site still up; the restart
# below is what takes it down. The trap removes the flag on any exit, failed or not, so a
# failed deploy never leaves the site stuck in maintenance.
MAINTENANCE_FLAG="${REPO_DIR}/maintenance/on"
mkdir -p "$(dirname "${MAINTENANCE_FLAG}")"
trap 'rm -f "${MAINTENANCE_FLAG}"' EXIT
echo "==> Maintenance page on"
touch "${MAINTENANCE_FLAG}"

echo "==> Starting services"
${COMPOSE} up -d --remove-orphans

# /ready, not /live: it also checks the database connection, so the maintenance page stays up
# until the new backend can actually serve requests.
echo "==> Waiting for backend to become ready"
timeout 90 bash -c "until ${COMPOSE} exec -T backend curl -sf http://localhost:8000/api/v1/health/ready; do sleep 3; done"

# The backend container already runs `migrate` before starting gunicorn (docker-compose.prod.yml),
# so this normally finds nothing to do; it stays as a check that the schema is current.
echo "==> Running migrations"
${COMPOSE} exec -T backend python manage.py migrate --noinput

echo "==> Maintenance page off"
rm -f "${MAINTENANCE_FLAG}"

echo "==> Removing dangling images"
docker image prune -f

echo "==> Deploy complete"
${COMPOSE} ps
